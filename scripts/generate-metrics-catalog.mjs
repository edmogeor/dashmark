import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { execFileSync } from 'node:child_process'
import yaml from 'js-yaml'
import { sourceWithDefaults } from './metric-utils.mjs'

const metricsDirectory = path.resolve('metrics')
const catalogPath = path.join(metricsDirectory, 'CATALOG.md')
const staged = process.argv.includes('--staged')

function metricFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) return metricFiles(file)
    return entry.name.endsWith('.yml') && entry.name !== 'provider.yml' ? [file] : []
  })
}

function credentialOptions(value, options = new Set()) {
  if (Array.isArray(value)) {
    value.forEach(item => credentialOptions(item, options))
    return options
  }
  if (value === null || typeof value !== 'object') return options

  const reference = value
  if (typeof reference.env === 'string' || typeof reference.file === 'string' || typeof reference.label === 'string') {
    options.add([reference.env, reference.file, reference.label].filter(item => typeof item === 'string').join(' or '))
  }
  Object.values(reference).forEach(item => credentialOptions(item, options))
  return options
}

function escapeCell(value) {
  return value.replaceAll('|', '\\|').replaceAll('\n', '<br>')
}

function metricInputs(parameters) {
  if (parameters === undefined) return 'None'
  return Object.entries(parameters)
    .map(([name, definition]) => `${name} (${definition.label})`)
    .join(', ')
}

function catalog() {
  const rows = []
  for (const file of metricFiles(metricsDirectory).sort()) {
    const metric = yaml.load(fs.readFileSync(file, 'utf8'))
    const directory = path.dirname(file)
    const providerPath = path.join(directory, 'provider.yml')
    const provider = fs.existsSync(providerPath) ? yaml.load(fs.readFileSync(providerPath, 'utf8')) : {}
    const relative = path.relative(metricsDirectory, file).split(path.sep)
    const source = sourceWithDefaults(provider, metric)
    const credentials = [...credentialOptions(source)]
      .map(credential => source.authentication?.optional === true ? `${credential} (optional)` : credential)
      .sort()
    rows.push([
      relative[0],
      path.basename(relative[1], '.yml'),
      metric.display.label,
      metricInputs(metric.parameters),
      credentials.length > 0 ? credentials.join(', ') : 'None'
    ])
  }

  const lines = [
    '<!-- Generated by scripts/generate-metrics-catalog.mjs. Do not edit manually. -->',
    '',
    '# Metric Catalog',
    '',
    'Credential options list the environment variables, secret files, or Docker labels declared by each metric. Entries marked optional are used only after an anonymous request receives HTTP 401 or 403. Inputs must be supplied under `metrics.catalog.<provider>.<metric>.inputs`.',
    '',
    '| Provider | Metric | Label | Required inputs | Credential options |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map(row => `| ${row.map(value => escapeCell(value)).join(' | ')} |`),
    ''
  ]
  return lines.join('\n')
}

const output = catalog()
if (staged && execFileSync('git', ['diff', '--cached', '--name-only', '--', ':(glob)metrics/**/*.yml'], { encoding: 'utf8' }).trim() === '') {
  process.exit(0)
}

if (process.argv.includes('--check')) {
  if (!fs.existsSync(catalogPath) || fs.readFileSync(catalogPath, 'utf8') !== output) {
    console.error('metrics/CATALOG.md is out of date. Run npm run generate:metrics-catalog.')
    process.exitCode = 1
  }
} else {
  fs.writeFileSync(catalogPath, output)
  if (staged) execFileSync('git', ['add', 'metrics/CATALOG.md'])
}
